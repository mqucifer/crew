"""The reference for the crew's records, generated from the code (crew#449, ADR 0014).

What a person or an experiment reads to know what a record's fields mean: the
context every record carries, the kinds of failure, the rules that decide, the
send-backs, and the event names. Written by `crew reference` into `docs/reference/records.md`;
a test regenerates it and compares, so the page and the code can't drift.
"""

from __future__ import annotations

from pathlib import Path

from crew_org import event_list, telemetry
from crew_org.events import FIELDS, EventKind
from crew_org.rules import Kind, Rule, meanings
from crew_org.sendbacks import CATALOG

ROOT = Path(__file__).resolve().parents[2]
PAGE = ROOT / "docs" / "reference" / "records.md"

# What each key of the common context means. Every record carries them where they
# apply: the log's records and the event log's lines under `ctx`; in Grafana, an
# event (from var/telemetry) as `<key>`, and a log line sent over OTLP as `crew_<key>`.
CONTEXT = {
    "tick": "The tick's id, unique across commands. Exported as `service.instance.id` too.",
    "commit": "The crew's commit that ran it. Exported as `service.version` too.",
    "dirty": "Whether the crew's tree had uncommitted changes.",
    "pass": "Which pass of the tick.",
    "phase": "The phase of the pass: refine, deliver, land and so on.",
    "run": "One role's work on one card in one phase. Its records share this id.",
    "role": "The role whose run it is.",
    "card": "The card the work is for.",
    "repo": "The card's repository.",
    "sprint": "The sprint it was in.",
    "attempt": "Which attempt at the card.",
    "for": "What the work was for, where there's no card: a retro, a review of a PR.",
    "trace_id": "The trace it was written in: a log line, an event and a span join on it.",
    "span_id": "The span it was written in.",
}


def _table(rows: dict[str, str], *, head: tuple[str, str]) -> list[str]:
    return [
        f"| {head[0]} | {head[1]} |",
        "|---|---|",
        *(f"| `{k}` | {v} |" for k, v in rows.items()),
    ]


def render() -> str:
    """The reference page, as committed."""
    kinds = meanings(Kind)
    rules = meanings(Rule)
    lines = [
        "# The crew's records: a reference",
        "",
        "Generated by `crew reference` from the code (crew#449). Don't edit it by hand.",
        "",
        "**Records join by ids, never by time or prose.** Every record carries the context",
        "below where it applies. A run's records, model calls and span share its `run`;",
        "a tick's share its `tick` and `commit`.",
        "",
        "## The context every record carries",
        "",
        *_table(CONTEXT, head=("Key", "Meaning")),
        "",
        "## Kinds of failure (`failure_kind`)",
        "",
        'What happened to the work. "Failed" alone reads as a model call failing, and',
        "usually wasn't one (crew#550).",
        "",
        *_table({k.value: kinds[k.name] for k in Kind}, head=("Kind", "Meaning")),
        "",
        "## The rules that decide (`rule`)",
        "",
        "Which of the crew's own rules decided a disposition, a block, a return or a hold.",
        "The record's summary says it for a person; the rule is what a count reads.",
        "",
        *_table({r.value: rules[r.name] for r in Rule}, head=("Rule", "Meaning")),
        "",
        "## Send-backs (`work.sent_back`)",
        "",
        "**A send-back** is a step's finished output that a check or a role sends back to",
        "the same step or an earlier one, to be done again: rework, counted per step",
        "(crew#862). Each writes one `work.sent_back`, with `sent_from`, `sent_to`, `rule`,",
        "the card, its `round` where the step knows it, and `counts`.",
        "",
        "**Its round** counts from 1, from what the step keeps: the session's round for the",
        "gates, the rebuilds for a merge conflict, the deliveries for the round-trip limit, and",
        "for CI, review and QA their returns of the pull request or card on GitHub. CI's",
        "comment marker is the same before review and at merge, so a CI return's round counts",
        "both together. None where the step keeps no count.",
        "",
        "**Not counted:** a refusal inside a session or a call (`tool.finished`,",
        "`llm.refused`); a hold, an interruption, or a retry of a step that didn't finish; a",
        "block for a person (`card.blocked`); a finding filed as a new Task or bug",
        "(`finding.filed`).",
        "",
        "| From | To | Rule | Meaning |",
        "|---|---|---|---|",
        *(
            f"| `{b.sent_from.value}` | `{b.sent_to.value}` | `{b.rule}` | {b.means} |"
            for b in CATALOG
        ),
        "",
        "## Events",
        "",
        "Every kind of event, in `var/events/*.jsonl` and mirrored into the log as",
        "`events.<kind>` (crew#870). **Fields** are the detail fields its writers name; the",
        "**bold** ones leave for telemetry (ADR 0010), the rest stay on this machine.",
        "**Written in** is the code that writes it today: a kind written nowhere is in past",
        "logs only. **delivery-history** is what the package makes of it, read from its own",
        "mapping: the event part it becomes, the function that reads it, or nothing.",
        "Its parts built from something else, not an event: "
        + ", ".join(f"`{p}`" for p in event_list.parts_from_elsewhere())
        + ".",
        "",
        "| Kind | Meaning | Fields | Written in | delivery-history |",
        "|---|---|---|---|---|",
        *_event_rows(),
        "",
        "### The rules notes name",
        "",
        "A `note` names the rule that decided it, where it names one. Each rule a note",
        "names, what it means, and where those notes are written:",
        "",
        "| Rule | Meaning | Written in |",
        "|---|---|---|",
        *_note_rule_rows(),
        "",
        "### Notes that name no rule",
        "",
        "Each, by where it's written, the fixed words of its summary (`…` where a value is",
        "filled in), and the fields it names.",
        "",
        "| Written in | Says | Fields |",
        "|---|---|---|",
        *_unruled_note_rows(),
        "",
    ]
    return "\n".join(lines)


def write(path: Path = PAGE) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(), encoding="utf-8")
    return path


def _field(name: str) -> str:
    return f"**`{name}`**" if name in telemetry.DETAIL else f"`{name}`"


def _event_rows() -> list[str]:
    if missing := event_list.undescribed():
        raise ValueError(f"event kinds with no meaning under them: {', '.join(missing)}")
    meant = meanings(EventKind)
    written = event_list.written()
    published = event_list.published()
    rows = []
    for kind in EventKind:
        meaning = meant[kind.name]
        if kind is EventKind.NOTE:
            meaning += (
                " See [the rules notes name](#the-rules-notes-name) and"
                " [notes that name no rule](#notes-that-name-no-rule)."
            )
        fields = ", ".join(_field(f) for f in FIELDS[kind]) or "—"
        sites = written.get(kind)
        where = (
            ", ".join(sorted({f"`{s.module}`" for s in sites.sites}))
            if sites and sites.sites
            else "nowhere: past logs only"
        )
        out = published.get(kind, "stays in the crew's log")
        rows.append(f"| `{kind.value}` | {meaning} | {fields} | {where} | {out} |")
    return rows


def _note_rule_rows() -> list[str]:
    by_rule: dict[str, set[str]] = {}
    for note in event_list.notes():
        if note.rule is not None:
            by_rule.setdefault(note.rule, set()).add(f"`{note.site}`")
    return [
        f"| `{rule}` | {event_list.rule_meaning(rule)} | {', '.join(sorted(sites))} |"
        for rule, sites in sorted(by_rule.items())
    ]


def _unruled_note_rows() -> list[str]:
    def cell(text: str) -> str:
        return text.replace("|", "\\|").replace("`", "'")

    rows = []
    for note in event_list.notes():
        if note.rule is None:
            fields = ", ".join(_field(f) for f in note.fields) or "—"
            rows.append(f"| `{note.site}` | {cell(note.words)} | {fields} |")
    return rows
